import { openCharacterCreation, enterWorld, continueGame } from './character-menu';
import {test,expect} from '@playwright/test';
test('Rogue seven-skill bar, Energy costs, stealth/trap counters and CS/EN reload',async({page})=>{
 await page.goto('./?view=iso');
 await page.locator('#menu-language').selectOption('en');
 await openCharacterCreation(page);
 await page.getByRole('button',{name:/Rogue/}).click();
 await enterWorld(page);
 await expect(page.getByText('Rogue · Level 1')).toBeVisible();
 await expect(page.getByRole('button',{name:'Dash'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Poison Blade'})).toBeVisible();
 const extras=page.locator('[data-rogue-ability]');
 await expect(extras).toHaveCount(5);
 await expect(page.getByRole('button',{name:'Backstab'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Multishot'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Shadow Step'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Poison Trap'})).toBeVisible();
 const fan=page.getByRole('button',{name:'Fan of Knives'});
 await expect(fan).toBeEnabled();
 await fan.click();
 await expect(fan).toBeDisabled();
 await expect(page.getByTestId('rogue-status')).toContainText('Traps: 0/3');
 await page.locator('#game-language').selectOption('cs');
 await expect(page.getByTestId('rogue-status')).toContainText('Pasti: 0/3');
 await expect(page.locator('[data-rogue-ability="backstab"]')).toHaveAttribute('aria-label','Bodnutí do zad');
 await page.getByRole('button',{name:'Uložit'}).click();
 await expect(page.getByRole('status')).toContainText('Postava uložena');
 await page.reload();
 await continueGame(page);
 await expect(page.getByTestId('rogue-status')).toContainText('Pasti: 0/3');
 await expect(extras).toHaveCount(5);
});
